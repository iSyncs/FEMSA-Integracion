-- FE1S-37 · Sesiones del usuario. La cookie lleva un token aleatorio; aquí solo se guarda su SHA-256.
IF OBJECT_ID('dbo.USER_SESSION') IS NULL
BEGIN
  CREATE TABLE dbo.USER_SESSION (
    user_session_id INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_USER_SESSION PRIMARY KEY,
    user_id INT NOT NULL CONSTRAINT FK_USER_SESSION_USER REFERENCES dbo.[USER](user_id),
    token_hash CHAR(64) NOT NULL CONSTRAINT UQ_USER_SESSION_TOKEN UNIQUE,
    created_at DATETIME2 NOT NULL CONSTRAINT DF_USER_SESSION_CREATED DEFAULT SYSUTCDATETIME(),
    expires_at DATETIME2 NOT NULL,
    revoked_at DATETIME2 NULL,
    ip VARCHAR(64) NULL,
    user_agent NVARCHAR(300) NULL
  );
  CREATE INDEX IX_USER_SESSION_USER ON dbo.USER_SESSION (user_id);
END
